import type { ModalityStatus } from '../../src/types/perception.js';

export interface OCRResult {
  text: string;
  hasText: boolean;
  confidence: number | null; // Truthful: null if not generated by actual engine
  engine: string;
}

export interface VisionResult {
  hasVisualContent: boolean;
  summary: string;
  objects: string[];
  dimensions?: { width: number; height: number };
  confidence: number | null; // Truthful: null
  engine: string;
}

export interface SpeechResult {
  text: string;
  durationSeconds?: number;
  engine: string;
  confidence: number | null;
}

/**
 * OCR Provider: Honest extraction
 * If an external native OCR binary (tesseract/ONNX-OCR) is not installed on the system,
 * it reports NOT_AVAILABLE and does not fabricate text.
 */
export class LocalOCRProvider {
  private available: boolean = false;
  private status: ModalityStatus = 'NOT_AVAILABLE';
  private engine: string = 'Local Pattern/Lightweight OCR';

  constructor() {
    // Check if external tesseract or native OCR is configured via environment
    if (process.env.NEXUS_OCR_PROVIDER === 'native_tesseract') {
      this.available = false; // Native binary not installed on base system
      this.status = 'NOT_AVAILABLE';
    } else {
      this.available = false;
      this.status = 'NOT_AVAILABLE';
    }
  }

  public isAvailable(): boolean {
    return this.available;
  }

  public getStatus(): ModalityStatus {
    return this.status;
  }

  public getEngine(): string {
    return this.engine;
  }

  public async extractText(_base64Image: string): Promise<OCRResult> {
    if (!this.available) {
      return {
        text: '',
        hasText: false,
        confidence: null,
        engine: 'OCR Not Configured',
      };
    }
    // Truthful: If native OCR is bound, invoke it; otherwise return empty
    return {
      text: '',
      hasText: false,
      confidence: null,
      engine: this.engine,
    };
  }
}

/**
 * Vision Provider: Honest visual structure inspection
 * Inspects dimensions and image header without fabricating scene/object detection.
 */
export class LocalVisionProvider {
  private available: boolean = false;
  private status: ModalityStatus = 'NOT_CONFIGURED';
  private engine: string = 'Header & Structural Frame Inspector';

  constructor() {
    // Real inspection: In Phase 3, visual inspection parses real image metadata (dimensions, mime, size)
    this.available = true;
    this.status = 'READY';
  }

  public isAvailable(): boolean {
    return this.available;
  }

  public getStatus(): ModalityStatus {
    return this.status;
  }

  public getEngine(): string {
    return this.engine;
  }

  public inspectFrame(base64Data: string): VisionResult {
    // Safely parse dimensions from base64 data URL header or byte buffer
    let width = 0;
    let height = 0;

    try {
      // Basic PNG header inspection (PNG bytes 16-24 hold width/height)
      const dataIndex = base64Data.indexOf(',');
      const rawBase64 = dataIndex !== -1 ? base64Data.slice(dataIndex + 1) : base64Data;
      const buffer = Buffer.from(rawBase64.slice(0, 100), 'base64');
      if (buffer.length >= 24 && buffer[0] === 0x89 && buffer[1] === 0x50) { // PNG signature
        width = buffer.readUInt32BE(16);
        height = buffer.readUInt32BE(20);
      }
    } catch {
      // ignore
    }

    return {
      hasVisualContent: true,
      summary: width > 0 && height > 0 
        ? `Captured visual frame (${width}x${height} px). No cloud transmission.`
        : 'Captured visual frame. Verified local boundary.',
      objects: [], // No fake object detection
      dimensions: width > 0 && height > 0 ? { width, height } : undefined,
      confidence: null, // Strictly null
      engine: this.engine,
    };
  }
}

